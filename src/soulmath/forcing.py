"""Generic ontology: Boolean-valued models, ultrafilter, forcing.

    V^B --U--> V[G],   G not in V,   only ||- is carried.

A Boolean-valued model is a finite set of propositions with values in
a Boolean algebra (here: the 2-element algebra extended with graded
values in [0, 1] under min/max/complement — the standard [0,1]-valued
intermediate used for the superposition regime). An ultrafilter U is
a maximal consistent selector: it picks, for every proposition, a
side, respecting conjunction and upward closure. Collapsing V^B by U
gives the two-valued extension V[G].

The generic filter G itself is never in the ground model and is never
carried; what is carried is the forcing relation ||- — the trace of
the extension, i.e. for each condition p and sentence phi, whether
p ||- phi.
"""
from __future__ import annotations

from dataclasses import dataclass, field


@dataclass
class BooleanModel:
    """V^B: proposition -> Boolean value in [0, 1]."""
    values: dict = field(default_factory=dict)

    def __post_init__(self):
        for k, v in self.values.items():
            if not 0.0 <= v <= 1.0:
                raise ValueError(f"value of {k!r} out of [0, 1]: {v}")

    def boolean_value(self, prop: str) -> float:
        return self.values.get(prop, 0.0)

    def forces(self, prop: str, threshold: float = 1.0) -> bool:
        """p ||- phi in the graded sense: [[phi]] >= threshold."""
        return self.boolean_value(prop) >= threshold


@dataclass
class Ultrafilter:
    """A maximal consistent set of propositions (the collapse U)."""
    members: frozenset = frozenset()

    def contains(self, prop: str) -> bool:
        return prop in self.members

    def collapse(self, model: BooleanModel) -> dict:
        """V^B --U--> V[G]: two-valued truth assignment.

        A proposition is true in V[G] iff it is in U (equivalently,
        iff its Boolean value is 1 and it is selected). Propositions
        with intermediate value and not in U collapse to False — the
        superposition resolves, it does not smuggle in extra truth.
        """
        return {p: (p in self.members and model.boolean_value(p) == 1.0)
                for p in model.values}

    @classmethod
    def from_true_values(cls, model: BooleanModel) -> "Ultrafilter":
        """The principal ultrafilter generated by the value-1 props."""
        return cls(frozenset(p for p, v in model.values.items() if v == 1.0))


def forcing_trace(model: BooleanModel, conditions) -> dict:
    """The carried trace ||-: {(condition, prop): forces?}.

    For each condition (a named proposition acting as a forcing
    condition) and each sentence, record whether the condition forces
    the sentence — i.e. [[condition -> sentence]] == 1 under the
    graded implication a -> b = max(1 - a, b).
    """
    trace = {}
    for cond in conditions:
        cv = model.boolean_value(cond)
        for prop in model.values:
            pv = model.boolean_value(prop)
            impl = max(1.0 - cv, pv)
            trace[(cond, prop)] = impl >= 1.0
    return trace
